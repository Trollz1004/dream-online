#!/usr/bin/env node
// Code map: writes one Markdown map of a repo so a lane can read where things live first.
// Node built-ins only. No packages, no outside service. Never opens a file whose name starts with .env.
//
// Usage: node ops/codemap/build-codemap.mjs <repo-folder> <name> [--out <file>]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const MAX_LINES = 399;

const SKIP_DIRS = new Set([
  'node_modules', 'dist', 'build', '.venv', 'venv', 'env', '.git', '__pycache__', '.next', '.nuxt', 'out',
  'coverage', '.cache', '.turbo', '.vercel', '.pytest_cache', '.mypy_cache', '.ruff_cache', 'graphify-out',
  'site-packages', 'bower_components', 'vendor', 'target', '.idea', '.vscode', 'tmp', 'temp',
]);
const KEEP_HIDDEN_DIRS = new Set(['.github', '.agents']);
const SKIP_DIR_RE = /(^|[-_.])(archive|archives|archived|generated|backup|backups)([-_.]|$)/i;

const BINARY_EXT = new Set([
  'png', 'jpg', 'jpeg', 'gif', 'webp', 'ico', 'bmp', 'tif', 'tiff', 'svgz', 'psd', 'ai', 'blend', 'blend1', 'fbx',
  'obj', 'glb', 'gltf', 'stl', 'dae', 'ktx', 'ktx2', 'hdr', 'exr', 'dds', 'mp3', 'wav', 'ogg', 'flac', 'm4a', 'aac',
  'mp4', 'webm', 'mov', 'avi', 'mkv', 'zip', 'gz', 'tgz', '7z', 'rar', 'tar', 'xz', 'bz2', 'exe', 'dll', 'so',
  'dylib', 'pdb', 'lib', 'a', 'o', 'obj', 'pdf', 'woff', 'woff2', 'ttf', 'otf', 'eot', 'wasm', 'bin', 'dat', 'db',
  'sqlite', 'sqlite3', 'pyc', 'pyo', 'class', 'jar', 'onnx', 'safetensors', 'pt', 'ckpt', 'npy', 'npz', 'pkl',
  'parquet', 'msi', 'iso', 'img', 'vhd', 'vhdx', 'lnk', 'ds_store',
]);
const GENERATED_NAME_RE = /(\.min\.(js|css)$|\.map$|\.d\.ts$|^package-lock\.json$|^pnpm-lock\.yaml$|^yarn\.lock$|^poetry\.lock$|^uv\.lock$|^Cargo\.lock$|\.lock$|\.generated\.|_pb2(_grpc)?\.py$|\.bundle\.js$|\.chunk\.js$)/i;
const GENERATED_HEAD_RE = /@generated|DO NOT EDIT|auto-generated|autogenerated by|this file is generated/i;

const CODE_EXT = new Set(['ts', 'tsx', 'js', 'jsx', 'mjs', 'cjs', 'py']);
const SOURCE_EXT = new Set([
  ...CODE_EXT, 'ps1', 'psm1', 'sh', 'bash', 'bat', 'cmd', 'vbs', 'go', 'rs', 'java', 'kt', 'cs', 'cpp', 'cc', 'c',
  'h', 'hpp', 'gd', 'vue', 'svelte', 'css', 'scss', 'html', 'sql', 'lua', 'rb', 'php', 'swift', 'glsl', 'wgsl',
]);
const SCRIPT_EXT = new Set(['ps1', 'psm1', 'sh', 'bash', 'bat', 'cmd', 'vbs', 'mjs', 'js', 'cjs', 'ts', 'py']);
const OPS_DIRS = new Set(['ops', 'scripts', 'script', 'tasks', 'cron', 'scheduled', 'jobs', 'bin', 'deploy', 'infra']);
const SCHEDULED_RE = /Register-ScheduledTask|schtasks(\.exe)?\s|New-ScheduledTaskTrigger|crontab|node-cron|cron\.schedule|^\s*-\s*cron\s*:|^\s*schedule\s*:/im;

// A line that holds a regex literal with alternation is a pattern, not a scheduled task.
const looksScheduled = (text) => text.split(/\r?\n/).some((l) => SCHEDULED_RE.test(l) && !/\/[^/\s]*\|[^/]*\//.test(l));

const MAX_READ_BYTES = 400 * 1024;
const MAX_FILES = 60000;
const MAX_DEPTH = 14;

// ---------- safety ----------

export function isEnvFileName(name) {
  return String(name).toLowerCase().startsWith('.env');
}

/** Masks anything that looks like a key, a private address, or a user folder. */
export function maskSecrets(text) {
  let s = String(text);
  s = s.replace(/[A-Za-z]:[\\/]+Users[\\/]+[^\\/\s"'`|)\]]+/gi, '%USERPROFILE%');
  s = s.replace(/\/(Users|home)\/[^/\s"'`|)\]]+/g, '~');
  s = s.replace(/\b(sk|pk|rk)[-_](live|test|proj|ant)?[-_]?[A-Za-z0-9_-]{16,}/g, 'XXXX');
  s = s.replace(/\b(ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{20,}/g, 'XXXX');
  s = s.replace(/\bgithub_pat_[A-Za-z0-9_]{20,}/g, 'XXXX');
  s = s.replace(/\bAKIA[0-9A-Z]{16}\b/g, 'XXXX');
  s = s.replace(/\bAIza[0-9A-Za-z_-]{30,}/g, 'XXXX');
  s = s.replace(/\bxox[abposr]-[A-Za-z0-9-]{10,}/g, 'XXXX');
  s = s.replace(/\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{4,}/g, 'XXXX');
  s = s.replace(/\b((?:api[_-]?key|apikey|token|secret|password|passwd|pwd|auth)[A-Za-z_]*\s*[=:]\s*)(['"]?)[^\s'"`,;)]{6,}\2/gi, '$1$2XXXX$2');
  s = s.replace(/\b[a-f0-9]{32,}\b/gi, (m) => (/[0-9]/.test(m) && /[a-f]/i.test(m) ? 'XXXX' : m));
  s = s.replace(/[A-Za-z0-9+/_=-]{32,}/g, (m) => (m.split(/[-_./+=]/).some((seg) => seg.length >= 20 && /[A-Z]/.test(seg) && /[a-z]/.test(seg) && /[0-9]/.test(seg)) ? 'XXXX' : m));
  s = s.replace(/\b(10\.\d{1,3}\.\d{1,3}\.\d{1,3}|192\.168\.\d{1,3}\.\d{1,3}|172\.(1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3}|100\.(6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.\d{1,3}\.\d{1,3})\b/g, 'XXXX');
  return s;
}

// ---------- names ----------

const OBSIDIAN_BAD = /[*"\\<>:|?#^[\]]/;
/** Obsidian link where a note of that name could exist, plain text otherwise. */
export function noteLink(p) {
  const segs = String(p).split('/');
  if (!p || segs.some((s) => !s || s.startsWith('.') || OBSIDIAN_BAD.test(s))) return '`' + p + '`';
  return `[[${p}]]`;
}

const ext = (name) => {
  const i = name.lastIndexOf('.');
  return i > 0 ? name.slice(i + 1).toLowerCase() : '';
};
const groupOf = (dir) => {
  if (!dir || dir === '.') return '(root)';
  return dir.split('/').slice(0, 2).join('/');
};
const isTestFile = (rel) => {
  const base = path.posix.basename(rel);
  return /\.(test|spec|tests)\.[a-z0-9]+$/i.test(base) || /^test_.*\.py$/i.test(base) || /_test\.py$/i.test(base)
    || /(^|\/)(__tests__|tests?)\//i.test(rel);
};
const oneLine = (s, n = 110) => {
  const t = String(s).replace(/\s+/g, ' ').trim();
  return t.length > n ? t.slice(0, n - 1) + '…' : t;
};

// ---------- walk ----------

function walk(root, ctx) {
  const files = [];
  const dirs = new Set(['']);
  const stack = [['', 0]];
  while (stack.length) {
    const [rel, depth] = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(path.join(root, rel), { withFileTypes: true });
    } catch (err) {
      ctx.warnings.push(`could not list ${rel || '(root)'}: ${err.code || err.message}`);
      continue;
    }
    for (const e of entries) {
      const name = e.name;
      const childRel = rel ? `${rel}/${name}` : name;
      if (e.isSymbolicLink()) continue;
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(name) || SKIP_DIR_RE.test(name)) { ctx.skipped.dirs++; continue; }
        if (name.startsWith('.') && !KEEP_HIDDEN_DIRS.has(name)) { ctx.skipped.dirs++; continue; }
        if (depth >= MAX_DEPTH) continue;
        dirs.add(childRel);
        stack.push([childRel, depth + 1]);
        continue;
      }
      if (!e.isFile()) continue;
      if (isEnvFileName(name)) { ctx.skipped.env++; continue; } // never opened, never listed
      if (name === '.git') continue; // worktree pointer file
      const x = ext(name);
      if (BINARY_EXT.has(x)) { ctx.skipped.binary++; continue; }
      if (GENERATED_NAME_RE.test(name)) { ctx.skipped.generated++; continue; }
      if (files.length >= MAX_FILES) { ctx.truncatedWalk = true; continue; }
      let size = 0;
      try { size = fs.statSync(path.join(root, childRel)).size; } catch { /* keep 0 */ }
      files.push({ rel: childRel, name, ext: x, dir: rel, size });
    }
  }
  files.sort((a, b) => a.rel.localeCompare(b.rel));
  return { files, dirs };
}

function makeReader(root, ctx, hook) {
  const cache = new Map();
  return function read(file) {
    if (cache.has(file.rel)) return cache.get(file.rel);
    let text = null;
    if (isEnvFileName(file.name)) { cache.set(file.rel, null); return null; }
    if (file.size > MAX_READ_BYTES) { cache.set(file.rel, null); return null; }
    try {
      if (hook) hook(file.rel);
      const buf = fs.readFileSync(path.join(root, file.rel));
      const head = buf.subarray(0, 8000);
      if (head.includes(0)) {
        ctx.skipped.binary++;
        file.binary = true;
      } else {
        text = buf.toString('utf8');
        if (GENERATED_HEAD_RE.test(text.slice(0, 400))) { ctx.skipped.generated++; file.generated = true; text = null; }
      }
    } catch (err) {
      ctx.warnings.push(`could not read ${file.rel}: ${err.code || err.message}`);
      file.broken = true;
    }
    cache.set(file.rel, text);
    return text;
  };
}

// ---------- extractors ----------

function readmeLine(text) {
  const lines = text.split(/\r?\n/);
  let inFence = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith('```')) { inFence = !inFence; continue; }
    if (inFence || !line || line.startsWith('<') || line.startsWith('![') || line.startsWith('[![') || /^[-=*_]{3,}$/.test(line)) continue;
    const clean = line.replace(/^#+\s*/, '').replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[*_`]/g, '').trim();
    if (!clean) continue;
    if (line.startsWith('#')) return oneLine(clean);
    const m = clean.match(/^(.+?[.!?])(\s|$)/);
    return oneLine(m ? m[1] : clean);
  }
  return '';
}

function firstComment(text) {
  const lines = text.split(/\r?\n/).slice(0, 30);
  let inBlock = false;
  const skip = (t) => !t || /^\.(SYNOPSIS|DESCRIPTION|NOTES|EXAMPLE|PARAMETER)\b/i.test(t) || /^(eslint|@ts-|prettier|type:|pylint|noqa|SPDX|Copyright|requires\b|region\b|endregion\b)/i.test(t) || t === 'use strict' || /^[<#>*\/"'=-]+$/.test(t);
  for (const raw of lines) {
    const line = raw.trim();
    if (inBlock) {
      if (/^(#>|\*\/|"""|''')/.test(line)) { inBlock = false; continue; }
      const t = line.replace(/^\*\s?/, '').replace(/(#>|\*\/|"""|''')$/, '').trim();
      if (/(#>|\*\/|"""|''')$/.test(line)) inBlock = false;
      if (skip(t)) continue;
      return oneLine(t);
    }
    if (!line || line.startsWith('#!') || /coding[:=]/.test(line) || /^@?echo off/i.test(line)) continue;
    const open = line.match(/^(<#|\/\*+|"""|''')\s*(.*)$/);
    if (open) {
      const rest = open[2].replace(/(#>|\*\/|"""|''')\s*$/, '').trim();
      if (!/(#>|\*\/|"""|''')\s*$/.test(open[2]) || !open[2]) inBlock = !/(#>|\*\/|"""|''')\s*$/.test(open[2]);
      if (!skip(rest)) return oneLine(rest);
      continue;
    }
    const m = line.match(/^(?:#|\/\/+|::|REM\s|')\s*(.*)$/i);
    if (!m) {
      if (/^(param\s*\(|\[CmdletBinding|Set-StrictMode|\$ErrorActionPreference|setlocal)/i.test(line)) continue;
      return '';
    }
    const t = m[1].replace(/^[-=*#\s]+/, '').trim();
    if (skip(t)) continue;
    return oneLine(t);
  }
  return '';
}

const JS_IMPORT_RES = [
  /(?:^|[\s;])(?:import|export)\s[^'"`;]*?\bfrom\s*['"]([^'"\n]+)['"]/g,
  /(?:^|[\s;])import\s*['"]([^'"\n]+)['"]/g,
  /\b(?:require|import)\s*\(\s*['"]([^'"\n]+)['"]\s*\)/g,
];

function jsImports(text) {
  const out = [];
  for (const re of JS_IMPORT_RES) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(text))) out.push(m[1]);
  }
  return out;
}

function pyImports(text) {
  const out = [];
  for (const line of text.split(/\r?\n/)) {
    let m = line.match(/^\s*from\s+(\.*[\w.]*)\s+import\b/);
    if (m) { out.push(m[1]); continue; }
    m = line.match(/^\s*import\s+([\w.]+(?:\s*,\s*[\w.]+)*)/);
    if (m) for (const part of m[1].split(',')) out.push(part.trim());
  }
  return out;
}

function resolveImportDir(file, spec, known) {
  if (file.ext === 'py') {
    const dots = spec.match(/^\.*/)[0].length;
    const mod = spec.slice(dots).split('.').filter(Boolean);
    if (dots > 0) {
      let base = file.dir.split('/').filter(Boolean);
      base = base.slice(0, Math.max(0, base.length - (dots - 1)));
      for (let n = mod.length; n >= 0; n--) {
        const p = [...base, ...mod.slice(0, n)].join('/');
        if (known.files.has(p + '.py')) return path.posix.dirname(p) === '.' ? '' : path.posix.dirname(p);
        if (known.dirs.has(p)) return p;
      }
      return null;
    }
    if (!mod.length) return null;
    const parts = file.dir.split('/').filter(Boolean);
    const bases = [];
    for (let i = parts.length; i >= 0; i--) bases.push(parts.slice(0, i).join('/'));
    for (const base of bases) {
      for (let n = mod.length; n >= 1; n--) {
        const p = [base, ...mod.slice(0, n)].filter(Boolean).join('/');
        if (known.files.has(p + '.py')) { const d = path.posix.dirname(p); return d === '.' ? '' : d; }
        if (known.dirs.has(p) && known.files.has(p + '/__init__.py')) return p;
      }
    }
    return null;
  }
  if (!spec.startsWith('./') && !spec.startsWith('../') && spec !== '.' && spec !== '..') return null;
  const target = path.posix.normalize(path.posix.join(file.dir || '.', spec.split('?')[0]));
  if (target.startsWith('..')) return null;
  const t = target === '.' ? '' : target;
  if (known.dirs.has(t)) return t;
  const d = path.posix.dirname(t);
  return d === '.' ? '' : d;
}

const ROUTE_RES = [
  // FastAPI / Flask / Express / Hono style: obj.method("/path")
  { re: /(?:^|[^\w$.])@?([A-Za-z_$][\w$]*)\.(get|post|put|delete|patch|options|head|all|api_route|websocket|route)\(\s*(?:\r?\n\s*)?(['"`])(\/[^'"`\n]*)\3([^\n]*)/g, kind: 'call' },
];

function extractRoutes(file, text) {
  const routes = [];
  const lines = text.split(/\r?\n/);
  lines.forEach((line, i) => {
    for (const { re } of ROUTE_RES) {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(line))) {
        const obj = m[1];
        let method = m[2].toUpperCase();
        if (/^(headers|params|searchParams|map|cache|store|localStorage|sessionStorage|url|formData|cookies|req|request|res|response|config|settings|env|process)$/i.test(obj)) continue;
        if (method === 'ROUTE' || method === 'API_ROUTE') {
          const mm = (m[5] || '').match(/methods\s*=\s*\[([^\]]*)\]/);
          method = mm ? mm[1].replace(/['"\s]/g, '').toUpperCase() : 'ANY';
        }
        if (method === 'ALL') method = 'ANY';
        if (method === 'WEBSOCKET') method = 'WS';
        routes.push({ method, path: m[4], file: file.rel, line: i + 1 });
      }
    }
    const u = line.match(/\b(?:pathname|url\.pathname|req\.url|request\.url|path)\s*===?\s*['"](\/[^'"]*)['"]/);
    if (u) {
      const mm = line.match(/method\s*===?\s*['"]([A-Z]+)['"]/);
      routes.push({ method: mm ? mm[1] : 'ANY', path: u[1], file: file.rel, line: i + 1 });
    }
  });
  return routes;
}

const SERVER_RE = /\.listen\s*\(|createServer\s*\(|uvicorn\.run\s*\(|\bserve\s*\(\s*\{|=\s*FastAPI\s*\(|new\s+Hono\s*\(|=\s*express\s*\(\s*\)|Flask\s*\(\s*__name__|HTTPServer\s*\(|web\.run_app\s*\(/;

function extractPorts(text) {
  const ports = new Set();
  const res = [
    /\.listen\s*\(\s*(\d{2,5})\b/g,
    /\bPORT\b[^\n=]*?(?:\|\||\?\?|,)\s*['"]?(\d{2,5})\b/g,
    /\bport\s*[=:]\s*['"]?(\d{2,5})\b/gi,
    /--port[ =](\d{2,5})\b/g,
    /\bPORT\s*=\s*['"]?(\d{2,5})\b/g,
  ];
  for (const re of res) {
    let m;
    while ((m = re.exec(text))) {
      const n = Number(m[1]);
      if (n >= 80 && n <= 65535) ports.add(n);
    }
  }
  return [...ports].sort((a, b) => a - b);
}

function parseJson(text) {
  try { return JSON.parse(text.replace(/^\uFEFF/, '')); } catch { return undefined; }
}

// ---------- build ----------

/**
 * Builds the code map.
 * @param {string} root repo folder
 * @param {string} name repo name used in the title
 * @param {{ onRead?: (rel: string) => void, now?: Date }} [opts]
 */
export function buildCodemap(root, name, opts = {}) {
  const t0 = Date.now();
  const ctx = { warnings: [], skipped: { dirs: 0, env: 0, binary: 0, generated: 0 }, truncatedWalk: false };
  const absRoot = path.resolve(root);
  if (!fs.existsSync(absRoot) || !fs.statSync(absRoot).isDirectory()) throw new Error('repo folder not found');
  const { files, dirs } = walk(absRoot, ctx);
  const read = makeReader(absRoot, ctx, opts.onRead);
  const known = { files: new Set(files.map((f) => f.rel)), dirs };

  // top folders
  const topDirs = [...dirs].filter((d) => d && !d.includes('/')).sort((a, b) => a.localeCompare(b));
  const folderInfo = topDirs.map((d) => {
    const inside = files.filter((f) => f.rel.startsWith(d + '/'));
    const readme = files.find((f) => f.dir === d && /^readme(\.md|\.markdown|\.txt)?$/i.test(f.name));
    let desc = '';
    if (readme) { const t = read(readme); if (t) desc = readmeLine(t); }
    if (!desc) {
      const counts = {};
      for (const f of inside) { const k = f.ext ? '.' + f.ext : '(no ext)'; counts[k] = (counts[k] || 0) + 1; }
      const top = Object.entries(counts).sort((a, b) => b[1] - a[1]).slice(0, 4).map(([k, v]) => `${v} ${k}`);
      desc = inside.length ? `${inside.length} files: ${top.join(', ')}` : 'empty after skips';
    } else {
      desc += ` (${inside.length} files)`;
    }
    return { d, desc };
  });
  const rootFiles = files.filter((f) => !f.dir).sort((a, b) => Number(a.name.startsWith('.')) - Number(b.name.startsWith('.')) || a.name.localeCompare(b.name));

  // package.json scripts
  const pkgs = [];
  for (const f of files.filter((x) => x.name === 'package.json' && x.dir.split('/').filter(Boolean).length <= 3)) {
    const t = read(f);
    if (t == null) continue;
    const j = parseJson(t);
    if (!j || typeof j !== 'object') { ctx.warnings.push(`broken JSON in ${f.rel}, skipped`); continue; }
    pkgs.push({ file: f, dir: f.dir, name: j.name || f.dir || name, scripts: j.scripts && typeof j.scripts === 'object' ? j.scripts : {} });
  }

  // code scan
  const servers = [];
  const routes = [];
  const pairCounts = new Map();
  const scheduled = new Set();
  for (const f of files) {
    const isCode = CODE_EXT.has(f.ext);
    const isScript = SCRIPT_EXT.has(f.ext) || (/\.ya?ml$/i.test(f.name) && f.dir.startsWith('.github/workflows'));
    if (!isCode && !isScript) continue;
    const text = read(f);
    if (text == null) continue;
    try {
      if (!isTestFile(f.rel) && looksScheduled(text)) scheduled.add(f.rel);
      if (!isCode) continue;
      if (!isTestFile(f.rel)) {
        if (SERVER_RE.test(text)) servers.push({ file: f, ports: extractPorts(text), main: /__name__\s*==\s*['"]__main__['"]/.test(text) });
        routes.push(...extractRoutes(f, text));
      }
      f.lines = text.split(/\n/).length;
      const specs = f.ext === 'py' ? pyImports(text) : jsImports(text);
      const from = groupOf(f.dir);
      for (const spec of specs) {
        const dir = resolveImportDir(f, spec, known);
        if (dir == null) continue;
        const to = groupOf(dir);
        if (to === from) continue;
        const key = `${from}\u0000${to}`;
        pairCounts.set(key, (pairCounts.get(key) || 0) + 1);
      }
    } catch (err) {
      ctx.warnings.push(`could not scan ${f.rel}: ${err.message}`);
    }
  }

  // tests
  const testFiles = files.filter((f) => isTestFile(f.rel) && (CODE_EXT.has(f.ext) || SOURCE_EXT.has(f.ext)));
  const testGroups = new Map();
  for (const f of testFiles) {
    const g = groupOf(f.dir);
    if (!testGroups.has(g)) testGroups.set(g, { count: 0, exts: new Set() });
    const tg = testGroups.get(g);
    tg.count++;
    tg.exts.add(f.ext);
  }
  const testScripts = [];
  for (const p of pkgs) for (const [k, v] of Object.entries(p.scripts)) if (/^test/i.test(k)) testScripts.push({ p, k, v: String(v) });

  // ops / scheduled scripts
  const opsFiles = files.filter((f) => {
    if (isTestFile(f.rel)) return false;
    const segs = f.dir.split('/');
    const inOps = segs.some((s) => OPS_DIRS.has(s.toLowerCase())) && SCRIPT_EXT.has(f.ext);
    const workflow = f.dir === '.github/workflows' && /\.ya?ml$/i.test(f.name);
    return inOps || workflow || scheduled.has(f.rel);
  }).sort((a, b) => Number(b.rel.startsWith('.github/')) - Number(a.rel.startsWith('.github/')) || Number(scheduled.has(b.rel)) - Number(scheduled.has(a.rel)) || Number(a.rel.startsWith('.')) - Number(b.rel.startsWith('.')) || a.rel.localeCompare(b.rel));

  const largest = files.filter((f) => SOURCE_EXT.has(f.ext) && !f.binary && !f.generated).sort((a, b) => b.size - a.size).slice(0, 15);
  const pairs = [...pairCounts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 40);
  const elapsedScan = Date.now() - t0;

  // ---------- render ----------
  const render = (L) => {
    const out = [];
    const now = (opts.now || new Date()).toISOString().slice(0, 10);
    out.push(`# Code map: ${name}`);
    out.push('');
    out.push(`Built ${now} by \`ops/codemap/build-codemap.mjs\`. ${files.length} files read in ${elapsedScan} ms. Skipped: ${ctx.skipped.dirs} folders, ${ctx.skipped.binary} binary, ${ctx.skipped.generated} generated, ${ctx.skipped.env} env files (never opened).${ctx.truncatedWalk ? ' Walk stopped at the file cap.' : ''}`);
    out.push('');

    out.push('## Top folders');
    out.push('');
    folderInfo.slice(0, L.folders).forEach(({ d, desc }) => out.push(`- ${noteLink(d)}: ${desc}`));
    if (folderInfo.length > L.folders) out.push(`- and ${folderInfo.length - L.folders} more folders`);
    out.push(`- (root): ${rootFiles.length} files, ${rootFiles.slice(0, 8).map((f) => noteLink(f.rel)).join(', ')}${rootFiles.length > 8 ? ', …' : ''}`);
    out.push('');

    out.push('## Entry points and how to run them');
    out.push('');
    if (!pkgs.length && !servers.length) out.push('- none found');
    let scriptLines = 0;
    for (const p of pkgs) {
      const entries = Object.entries(p.scripts);
      if (!entries.length) continue;
      if (scriptLines >= L.scripts) { out.push(`- ${noteLink(p.file.rel)}: ${entries.length} scripts (not listed)`); continue; }
      out.push(`- ${noteLink(p.file.rel)}${p.dir ? ` (run from ${noteLink(p.dir)})` : ''}:`);
      for (const [k, v] of entries) {
        if (scriptLines >= L.scripts) { out.push(`  - and ${entries.length - entries.indexOf(entries.find(([kk]) => kk === k))} more`); break; }
        out.push(`  - \`npm run ${k}\`: \`${oneLine(String(v), 90).replace(/`/g, "'")}\``);
        scriptLines++;
      }
    }
    if (servers.length) {
      out.push('- Server files:');
      for (const s of servers.slice(0, L.servers)) {
        const base = s.file.name.replace(/\.[^.]+$/, '');
        const script = pkgs.flatMap((p) => Object.entries(p.scripts).map(([k, v]) => ({ k, v: String(v) }))).find(({ v }) => v.includes(s.file.name) || v.includes(base + '.'));
        let how;
        if (script) how = `npm run ${script.k}`;
        else if (s.file.ext === 'py') how = s.main ? `python ${s.file.rel}` : `uvicorn ${s.file.rel.replace(/\.py$/, '').replace(/\//g, '.')}:app`;
        else if (s.file.ext === 'ts' || s.file.ext === 'tsx') how = `npx tsx ${s.file.rel}`;
        else how = `node ${s.file.rel}`;
        out.push(`  - ${noteLink(s.file.rel)}: port ${s.ports.length ? s.ports.join(', ') : 'not found'}; run \`${how}\``);
      }
      if (servers.length > L.servers) out.push(`  - and ${servers.length - L.servers} more server files`);
    }
    out.push('');

    out.push('## HTTP routes');
    out.push('');
    if (!routes.length) out.push('- none found');
    else {
      out.push('| Method | Path | File |');
      out.push('| --- | --- | --- |');
      for (const r of routes.slice(0, L.routes)) out.push(`| ${r.method} | \`${r.path.replace(/\|/g, '\\|').replace(/`/g, "'")}\` | ${noteLink(r.file)} line ${r.line} |`);
      if (routes.length > L.routes) {
        const rest = new Map();
        for (const r of routes.slice(L.routes)) rest.set(r.file, (rest.get(r.file) || 0) + 1);
        out.push('');
        out.push(`${routes.length - L.routes} more routes: ${[...rest.entries()].sort((a, b) => b[1] - a[1]).slice(0, 8).map(([f, n]) => `${noteLink(f)} (${n})`).join(', ')}${rest.size > 8 ? ', …' : ''}`);
      }
    }
    out.push('');

    out.push('## Which folder imports which');
    out.push('');
    if (!pairs.length) out.push('- no imports between folders found');
    else {
      out.push('| From | To | Imports |');
      out.push('| --- | --- | --- |');
      for (const [k, n] of pairs) {
        const [a, b] = k.split('\u0000');
        out.push(`| ${a === '(root)' ? a : noteLink(a)} | ${b === '(root)' ? b : noteLink(b)} | ${n} |`);
      }
    }
    out.push('');

    out.push('## Tests');
    out.push('');
    if (!testGroups.size) out.push('- no test files found');
    const groups = [...testGroups.entries()].sort((a, b) => b[1].count - a[1].count);
    for (const [g, info] of groups.slice(0, L.tests)) {
      const script = testScripts.find(({ v }) => g !== '(root)' && v.includes(g));
      let how;
      if (script) how = `npm run ${script.k}${script.p.dir ? ` (in ${script.p.dir})` : ''}`;
      else if (info.exts.has('py')) how = `python -m pytest ${g === '(root)' ? '.' : g}`;
      else if (info.exts.has('ts') || info.exts.has('tsx')) how = `node --import tsx --test ${g === '(root)' ? '' : g + '/'}**/*.test.ts`;
      else how = `node --test ${g === '(root)' ? '.' : g}`;
      out.push(`- ${g === '(root)' ? g : noteLink(g)}: ${info.count} test files (${[...info.exts].join(', ')}); run \`${how}\``);
    }
    if (groups.length > L.tests) out.push(`- and ${groups.length - L.tests} more test folders`);
    for (const { p, k, v } of testScripts.slice(0, 6)) out.push(`- \`npm run ${k}\`${p.dir ? ` in ${noteLink(p.dir)}` : ''}: \`${oneLine(v, 100).replace(/`/g, "'")}\``);
    out.push('');

    out.push('## Ops and scheduled-task scripts');
    out.push('');
    if (!opsFiles.length) out.push('- none found');
    for (const f of opsFiles.slice(0, L.ops)) {
      const t = read(f);
      const yamlName = t && /\.ya?ml$/i.test(f.name) ? (t.match(/^name:\s*['"]?(.+?)['"]?\s*$/m) || [])[1] : '';
      const desc = (yamlName && `workflow: ${oneLine(yamlName)}`) || (t && firstComment(t)) || `${f.ext || 'file'} script`;
      out.push(`- ${noteLink(f.rel)}${scheduled.has(f.rel) ? ' (scheduled)' : ''}: ${desc}`);
    }
    if (opsFiles.length > L.ops) {
      const rest = new Map();
      for (const f of opsFiles.slice(L.ops)) { const g = groupOf(f.dir); rest.set(g, (rest.get(g) || 0) + 1); }
      out.push(`- and ${opsFiles.length - L.ops} more: ${[...rest.entries()].sort((a, b) => b[1] - a[1]).slice(0, 8).map(([g, n]) => `${g} (${n})`).join(', ')}`);
    }
    out.push('');

    out.push('## 15 largest source files');
    out.push('');
    largest.forEach((f, i) => out.push(`${i + 1}. ${noteLink(f.rel)}: ${(f.size / 1024).toFixed(1)} KB${f.lines ? `, ${f.lines} lines` : ''}`));
    if (!largest.length) out.push('- none found');
    if (ctx.warnings.length) {
      out.push('');
      out.push('## Build warnings');
      out.push('');
      ctx.warnings.slice(0, 5).forEach((w) => out.push(`- ${oneLine(w, 140)}`));
      if (ctx.warnings.length > 5) out.push(`- and ${ctx.warnings.length - 5} more`);
    }
    return out.map(maskSecrets);
  };

  let L = { folders: 40, scripts: 45, servers: 20, routes: 90, tests: 20, ops: 70 };
  let lines = render(L);
  for (let i = 0; i < 12 && lines.length > MAX_LINES; i++) {
    for (const k of Object.keys(L)) L[k] = Math.max(3, Math.floor(L[k] * 0.8));
    lines = render(L);
  }
  if (lines.length > MAX_LINES) lines = [...lines.slice(0, MAX_LINES - 1), '_Map cut at the line limit._'];
  return {
    markdown: lines.join('\n') + '\n',
    stats: { files: files.length, routes: routes.length, servers: servers.length, pairs: pairs.length, ms: Date.now() - t0, lines: lines.length },
    warnings: ctx.warnings,
  };
}

// ---------- CLI ----------

function main(argv) {
  const args = argv.slice(2);
  const outIdx = args.indexOf('--out');
  let out = null;
  if (outIdx >= 0) { out = args[outIdx + 1]; args.splice(outIdx, 2); }
  const [root, name] = args;
  if (!root || !name) {
    process.stderr.write('usage: node ops/codemap/build-codemap.mjs <repo-folder> <name> [--out <file>]\n');
    return 2;
  }
  const result = buildCodemap(root, name);
  if (out) {
    fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
    fs.writeFileSync(out, result.markdown);
    process.stdout.write(`wrote ${result.stats.lines} lines for ${name}: ${result.stats.files} files, ${result.stats.routes} routes, ${result.stats.pairs} folder pairs in ${result.stats.ms} ms\n`);
  } else {
    process.stdout.write(result.markdown);
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv);
  } catch (err) {
    process.stderr.write(`codemap failed: ${maskSecrets(err.message)}\n`);
    process.exitCode = 1;
  }
}
